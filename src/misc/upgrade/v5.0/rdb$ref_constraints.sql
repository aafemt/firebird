create or alter view PUBLIC.RDB$REF_CONSTRAINTS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
REF_CONSTRAINTS As (
  Select distinct
    first_value(RDB$CONSTRAINT_NAME) over Win as CONSTRAINT_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$REF_CONSTRAINTS r
    join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME
  Window Win As (partition by r.RDB$CONSTRAINT_NAME order by p.PRIO)
)
SELECT a.RDB$CONSTRAINT_NAME, a.RDB$CONST_NAME_UQ, a.RDB$MATCH_OPTION,
    a.RDB$UPDATE_RULE, a.RDB$DELETE_RULE
FROM SYSTEM.RDB$REF_CONSTRAINTS a join REF_CONSTRAINTS
  on a.RDB$CONSTRAINT_NAME=CONSTRAINT_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$REF_CONSTRAINTS to PUBLIC;
