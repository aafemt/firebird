create or alter view PUBLIC.RDB$USER_PRIVILEGES as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
USER_PRIVILEGES As (
  Select distinct
    first_value(RDB$USER) over Win as USER_NAME,
    first_value(RDB$RELATION_NAME) over Win as RELATION_NAME,
    first_value(RDB$RELATION_SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$USER_PRIVILEGES u
    join SEARCH_PATH p on p.SCHEMA_NAME = u.RDB$RELATION_SCHEMA_NAME and p.SCHEMA_NAME = u.RDB$USER_SCHEMA_NAME
  Window Win As (partition by u.RDB$USER,u.RDB$RELATION_NAME order by p.PRIO)
)
SELECT a.RDB$USER, a.RDB$GRANTOR, a.RDB$PRIVILEGE, a.RDB$GRANT_OPTION,
    a.RDB$RELATION_NAME, a.RDB$FIELD_NAME, a.RDB$USER_TYPE, a.RDB$OBJECT_TYPE
FROM SYSTEM.RDB$USER_PRIVILEGES a join USER_PRIVILEGES
  on a.RDB$USER=USER_NAME and
     a.RDB$RELATION_NAME=RELATION_NAME and
     a.RDB$USER_SCHEMA_NAME=SCHEMA_NAME and
     a.RDB$RELATION_SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$USER_PRIVILEGES to PUBLIC;
