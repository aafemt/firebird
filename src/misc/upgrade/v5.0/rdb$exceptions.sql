create or alter view PUBLIC.RDB$EXCEPTIONS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
EXCEPTIONS As (
  Select distinct
    first_value(RDB$EXCEPTION_NAME) over Win as EXCEPTION_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$EXCEPTIONS e
    join SEARCH_PATH p on p.SCHEMA_NAME = e.RDB$SCHEMA_NAME
  Window Win As (partition by e.RDB$EXCEPTION_NAME order by p.PRIO)
)
SELECT a.RDB$EXCEPTION_NAME, a.RDB$EXCEPTION_NUMBER, a.RDB$MESSAGE,
    a.RDB$DESCRIPTION, a.RDB$SYSTEM_FLAG, a.RDB$SECURITY_CLASS, a.RDB$OWNER_NAME
FROM SYSTEM.RDB$EXCEPTIONS a join EXCEPTIONS
  on a.RDB$EXCEPTION_NAME=EXCEPTION_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$EXCEPTIONS to PUBLIC;
