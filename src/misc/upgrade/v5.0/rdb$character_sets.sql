create or alter view PUBLIC.RDB$CHARACTER_SETS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
CHARSETS As (
  Select distinct
    first_value(RDB$CHARACTER_SET_ID) over Win as CHARSET_ID
  from SYSTEM.RDB$CHARACTER_SETS c
    join SEARCH_PATH p on p.SCHEMA_NAME = c.RDB$SCHEMA_NAME
  Window Win As (partition by c.RDB$CHARACTER_SET_NAME order by p.PRIO)
)
SELECT a.RDB$CHARACTER_SET_NAME, a.RDB$FORM_OF_USE, a.RDB$NUMBER_OF_CHARACTERS,
    a.RDB$DEFAULT_COLLATE_NAME, a.RDB$CHARACTER_SET_ID, a.RDB$SYSTEM_FLAG,
    a.RDB$DESCRIPTION, a.RDB$FUNCTION_NAME, a.RDB$BYTES_PER_CHARACTER,
    a.RDB$SECURITY_CLASS, a.RDB$OWNER_NAME
FROM SYSTEM.RDB$CHARACTER_SETS a join CHARSETS
  on a.RDB$CHARACTER_SET_ID=CHARSET_ID;

grant SELECT on table PUBLIC.RDB$CHARACTER_SETS to PUBLIC;
