create or alter view PUBLIC.RDB$TRIGGERS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
TRIGGERS As (
  Select distinct
    first_value(RDB$TRIGGER_NAME) over Win as TRIGGER_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$TRIGGERS r
    join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME
  Window Win As (partition by r.RDB$TRIGGER_NAME order by p.PRIO)
)
SELECT a.RDB$TRIGGER_NAME, a.RDB$RELATION_NAME, a.RDB$TRIGGER_SEQUENCE,
    a.RDB$TRIGGER_TYPE, a.RDB$TRIGGER_SOURCE, a.RDB$TRIGGER_BLR,
    a.RDB$DESCRIPTION, a.RDB$TRIGGER_INACTIVE, a.RDB$SYSTEM_FLAG, a.RDB$FLAGS,
    a.RDB$VALID_BLR, a.RDB$DEBUG_INFO, a.RDB$ENGINE_NAME, a.RDB$ENTRYPOINT,
    a.RDB$SQL_SECURITY
FROM SYSTEM.RDB$TRIGGERS a join TRIGGERS
  on a.RDB$TRIGGER_NAME=TRIGGER_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$TRIGGERS to PUBLIC;
