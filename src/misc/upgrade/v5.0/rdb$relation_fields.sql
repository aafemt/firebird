create or alter view PUBLIC.RDB$RELATION_FIELDS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
RELATIONS As (
  Select distinct
    first_value(RDB$RELATION_NAME) over Win as RELATION_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$RELATIONS r
    join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME and r.RDB$PACKAGE_NAME is null
  Window Win As (partition by r.RDB$RELATION_NAME order by p.PRIO)
)
SELECT a.RDB$FIELD_NAME, a.RDB$RELATION_NAME, a.RDB$FIELD_SOURCE,
    a.RDB$QUERY_NAME, a.RDB$BASE_FIELD, a.RDB$EDIT_STRING, a.RDB$FIELD_POSITION,
    a.RDB$QUERY_HEADER, a.RDB$UPDATE_FLAG, a.RDB$FIELD_ID, a.RDB$VIEW_CONTEXT,
    a.RDB$DESCRIPTION, a.RDB$DEFAULT_VALUE, a.RDB$SYSTEM_FLAG,
    a.RDB$SECURITY_CLASS, a.RDB$COMPLEX_NAME, a.RDB$NULL_FLAG,
    a.RDB$DEFAULT_SOURCE, a.RDB$COLLATION_ID, a.RDB$GENERATOR_NAME,
    a.RDB$IDENTITY_TYPE
FROM SYSTEM.RDB$RELATION_FIELDS a join RELATIONS
  on a.RDB$RELATION_NAME=RELATION_NAME and
     a.RDB$PACKAGE_NAME is null and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$RELATION_FIELDS to PUBLIC;
