create or alter view PUBLIC.RDB$FUNCTION_ARGUMENTS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
FUNCTIONS As (
  Select distinct
    first_value(RDB$FUNCTION_NAME) over Win as FUNCTION_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$FUNCTION_ARGUMENTS f
    join SEARCH_PATH p on p.SCHEMA_NAME = f.RDB$SCHEMA_NAME
  Window Win As (partition by f.RDB$FUNCTION_NAME order by p.PRIO)
)
SELECT a.RDB$FUNCTION_NAME, a.RDB$ARGUMENT_POSITION, a.RDB$MECHANISM,
    a.RDB$FIELD_TYPE, a.RDB$FIELD_SCALE, a.RDB$FIELD_LENGTH,
    a.RDB$FIELD_SUB_TYPE, a.RDB$CHARACTER_SET_ID, a.RDB$FIELD_PRECISION,
    a.RDB$CHARACTER_LENGTH, a.RDB$PACKAGE_NAME, a.RDB$ARGUMENT_NAME,
    a.RDB$FIELD_SOURCE, a.RDB$DEFAULT_VALUE, a.RDB$DEFAULT_SOURCE,
    a.RDB$COLLATION_ID, a.RDB$NULL_FLAG, a.RDB$ARGUMENT_MECHANISM,
    a.RDB$FIELD_NAME, a.RDB$RELATION_NAME, a.RDB$SYSTEM_FLAG, a.RDB$DESCRIPTION
FROM SYSTEM.RDB$FUNCTION_ARGUMENTS a join FUNCTIONS
  on a.RDB$FUNCTION_NAME=FUNCTION_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$FUNCTION_ARGUMENTS to PUBLIC;
