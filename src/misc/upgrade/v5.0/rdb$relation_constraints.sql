create or alter view PUBLIC.RDB$RELATION_CONSTRAINTS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
RELATIONS As (
  Select distinct
    first_value(RDB$RELATION_NAME) over Win as RELATION_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$RELATION_CONSTRAINTS r
    join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME
  Window Win As (partition by r.RDB$RELATION_NAME order by p.PRIO)
)
SELECT a.RDB$CONSTRAINT_NAME, a.RDB$CONSTRAINT_TYPE, a.RDB$RELATION_NAME,
    a.RDB$DEFERRABLE, a.RDB$INITIALLY_DEFERRED, a.RDB$INDEX_NAME
FROM SYSTEM.RDB$RELATION_CONSTRAINTS a join RELATIONS
  on a.RDB$RELATION_NAME=RELATION_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$RELATION_CONSTRAINTS to PUBLIC;
