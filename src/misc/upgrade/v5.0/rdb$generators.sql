create or alter view PUBLIC.RDB$GENERATORS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
GENERATOR_IDS As (
  Select distinct first_value(RDB$GENERATOR_ID) over (partition by g.RDB$GENERATOR_NAME order by p.PRIO) as GENERATOR_ID
  from SYSTEM.RDB$GENERATORS g join SEARCH_PATH p on p.SCHEMA_NAME = g.RDB$SCHEMA_NAME
)
SELECT a.RDB$GENERATOR_NAME, a.RDB$GENERATOR_ID, a.RDB$SYSTEM_FLAG,
    a.RDB$DESCRIPTION, a.RDB$SECURITY_CLASS, a.RDB$OWNER_NAME,
    a.RDB$INITIAL_VALUE, a.RDB$GENERATOR_INCREMENT
FROM SYSTEM.RDB$GENERATORS a join GENERATOR_IDS
  on a.RDB$GENERATOR_ID = GENERATOR_ID;

grant SELECT on table PUBLIC.RDB$GENERATORS to PUBLIC;
