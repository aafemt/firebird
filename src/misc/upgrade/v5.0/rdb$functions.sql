create or alter view PUBLIC.RDB$FUNCTIONS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
FUNCTIONS As (
  Select distinct
    first_value(RDB$FUNCTION_NAME) over Win as FUNCTION_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$FUNCTIONS f
    join SEARCH_PATH p on p.SCHEMA_NAME = f.RDB$SCHEMA_NAME
  Window Win As (partition by f.RDB$FUNCTION_NAME order by p.PRIO)
)
SELECT a.RDB$FUNCTION_NAME, a.RDB$FUNCTION_TYPE, a.RDB$QUERY_NAME,
    a.RDB$DESCRIPTION, a.RDB$MODULE_NAME, a.RDB$ENTRYPOINT,
    a.RDB$RETURN_ARGUMENT, a.RDB$SYSTEM_FLAG, a.RDB$ENGINE_NAME,
    a.RDB$PACKAGE_NAME, a.RDB$PRIVATE_FLAG, a.RDB$FUNCTION_SOURCE,
    a.RDB$FUNCTION_ID, a.RDB$FUNCTION_BLR, a.RDB$VALID_BLR, a.RDB$DEBUG_INFO,
    a.RDB$SECURITY_CLASS, a.RDB$OWNER_NAME, a.RDB$LEGACY_FLAG,
    a.RDB$DETERMINISTIC_FLAG, a.RDB$SQL_SECURITY
FROM SYSTEM.RDB$FUNCTIONS a join FUNCTIONS
  on a.RDB$FUNCTION_NAME=FUNCTION_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$FUNCTIONS to PUBLIC;
