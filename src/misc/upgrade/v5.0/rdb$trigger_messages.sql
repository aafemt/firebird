create or alter view PUBLIC.RDB$TRIGGER_MESSAGES as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
TRIGGER_MESSAGES As (
  Select distinct
    first_value(RDB$TRIGGER_NAME) over Win as TRIGGER_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$TRIGGER_MESSAGES r
    join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME
  Window Win As (partition by r.RDB$TRIGGER_NAME order by p.PRIO)
)
SELECT a.RDB$TRIGGER_NAME, a.RDB$MESSAGE_NUMBER, a.RDB$MESSAGE
FROM SYSTEM.RDB$TRIGGER_MESSAGES a join TRIGGER_MESSAGES
  on a.RDB$TRIGGER_NAME=TRIGGER_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$TRIGGER_MESSAGES to PUBLIC;
