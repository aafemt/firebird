create or alter view PUBLIC.RDB$RELATIONS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
RELATION_IDS As (
  Select distinct first_value(RDB$RELATION_ID) over (partition by r.RDB$RELATION_NAME order by p.PRIO) as RELATION_ID from SYSTEM.RDB$RELATIONS r join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME and r.RDB$PACKAGE_NAME is null
)
SELECT a.RDB$VIEW_BLR, a.RDB$VIEW_SOURCE, a.RDB$DESCRIPTION, a.RDB$RELATION_ID,
    a.RDB$SYSTEM_FLAG, a.RDB$DBKEY_LENGTH, a.RDB$FORMAT, a.RDB$FIELD_ID,
    a.RDB$RELATION_NAME, a.RDB$SECURITY_CLASS, a.RDB$EXTERNAL_FILE,
    a.RDB$RUNTIME, a.RDB$EXTERNAL_DESCRIPTION, a.RDB$OWNER_NAME,
    a.RDB$DEFAULT_CLASS, a.RDB$FLAGS, a.RDB$RELATION_TYPE, a.RDB$SQL_SECURITY
FROM SYSTEM.RDB$RELATIONS a join RELATION_IDS
  on a.RDB$RELATION_ID = RELATION_ID;

grant SELECT on table PUBLIC.RDB$RELATIONS to PUBLIC;
