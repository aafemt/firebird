create or alter view PUBLIC.RDB$PACKAGES as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
PACKAGE_IDS As (
  Select distinct first_value(RDB$PACKAGE_ID) over (partition by r.RDB$PACKAGE_NAME order by p.PRIO) as PACKAGE_ID
  from SYSTEM.RDB$PACKAGES r join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME
)
SELECT a.RDB$PACKAGE_NAME, a.RDB$PACKAGE_HEADER_SOURCE,
    a.RDB$PACKAGE_BODY_SOURCE, a.RDB$VALID_BODY_FLAG, a.RDB$SECURITY_CLASS,
    a.RDB$OWNER_NAME, a.RDB$SYSTEM_FLAG, a.RDB$DESCRIPTION, a.RDB$SQL_SECURITY
FROM SYSTEM.RDB$PACKAGES a join PACKAGE_IDS
  on a.RDB$PACKAGE_ID = PACKAGE_ID;

grant SELECT on table PUBLIC.RDB$PACKAGES to PUBLIC;
