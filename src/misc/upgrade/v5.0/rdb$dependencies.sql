create or alter view PUBLIC.RDB$DEPENDENCIES as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
DEPENDENCIES As (
  Select distinct
    first_value(RDB$DEPENDENT_NAME) over Win as DEPENDENT_NAME,
    first_value(RDB$DEPENDENT_SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$DEPENDENCIES d
    join SEARCH_PATH p on p.SCHEMA_NAME = d.RDB$DEPENDENT_SCHEMA_NAME
  Window Win As (partition by d.RDB$DEPENDENT_NAME order by p.PRIO)
)

SELECT a.RDB$DEPENDENT_NAME, a.RDB$DEPENDED_ON_NAME, a.RDB$FIELD_NAME,
    a.RDB$DEPENDENT_TYPE, a.RDB$DEPENDED_ON_TYPE, a.RDB$PACKAGE_NAME
FROM SYSTEM.RDB$DEPENDENCIES a join DEPENDENCIES
  on a.RDB$DEPENDENT_NAME=DEPENDENT_NAME and
     a.RDB$DEPENDENT_SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$DEPENDENCIES to PUBLIC;
