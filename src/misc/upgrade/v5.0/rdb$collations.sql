create or alter view PUBLIC.RDB$COLLATIONS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
COLLATIONS As (
  Select distinct
    first_value(RDB$COLLATION_NAME) over Win as COLLATION_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$COLLATIONS c
    join SEARCH_PATH p on p.SCHEMA_NAME = c.RDB$SCHEMA_NAME
  Window Win As (partition by c.RDB$COLLATION_NAME order by p.PRIO)
)
SELECT a.RDB$COLLATION_NAME, a.RDB$COLLATION_ID, a.RDB$CHARACTER_SET_ID,
    a.RDB$COLLATION_ATTRIBUTES, a.RDB$SYSTEM_FLAG, a.RDB$DESCRIPTION,
    a.RDB$FUNCTION_NAME, a.RDB$BASE_COLLATION_NAME, a.RDB$SPECIFIC_ATTRIBUTES,
    a.RDB$SECURITY_CLASS, a.RDB$OWNER_NAME
FROM SYSTEM.RDB$COLLATIONS a join COLLATIONS
  on a.RDB$COLLATION_NAME=COLLATION_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$COLLATIONS to PUBLIC;
