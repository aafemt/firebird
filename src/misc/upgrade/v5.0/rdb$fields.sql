create or alter view PUBLIC.RDB$FIELDS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
FIELDS As (
  Select distinct
    first_value(RDB$FIELD_NAME) over Win as FIELD_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$FIELDS f
    join SEARCH_PATH p on p.SCHEMA_NAME = f.RDB$SCHEMA_NAME
  Window Win As (partition by f.RDB$FIELD_NAME order by p.PRIO)
)
SELECT a.RDB$FIELD_NAME, a.RDB$QUERY_NAME, a.RDB$VALIDATION_BLR,
    a.RDB$VALIDATION_SOURCE, a.RDB$COMPUTED_BLR, a.RDB$COMPUTED_SOURCE,
    a.RDB$DEFAULT_VALUE, a.RDB$DEFAULT_SOURCE, a.RDB$FIELD_LENGTH,
    a.RDB$FIELD_SCALE, a.RDB$FIELD_TYPE, a.RDB$FIELD_SUB_TYPE,
    a.RDB$MISSING_VALUE, a.RDB$MISSING_SOURCE, a.RDB$DESCRIPTION,
    a.RDB$SYSTEM_FLAG, a.RDB$QUERY_HEADER, a.RDB$SEGMENT_LENGTH,
    a.RDB$EDIT_STRING, a.RDB$EXTERNAL_LENGTH, a.RDB$EXTERNAL_SCALE,
    a.RDB$EXTERNAL_TYPE, a.RDB$DIMENSIONS, a.RDB$NULL_FLAG,
    a.RDB$CHARACTER_LENGTH, a.RDB$COLLATION_ID, a.RDB$CHARACTER_SET_ID,
    a.RDB$FIELD_PRECISION, a.RDB$SECURITY_CLASS, a.RDB$OWNER_NAME
FROM SYSTEM.RDB$FIELDS a join FIELDS
  on a.RDB$FIELD_NAME=FIELD_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$FIELDS to PUBLIC;
