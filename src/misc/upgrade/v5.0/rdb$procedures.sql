create or alter view PUBLIC.RDB$PROCEDURES as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
PROCEDURE_IDS As (
  Select distinct first_value(RDB$PROCEDURE_ID) over (partition by r.RDB$PROCEDURE_NAME order by p.PRIO) as PROCEDURE_ID from SYSTEM.RDB$PROCEDURES r join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME
)
SELECT a.RDB$PROCEDURE_NAME, a.RDB$PROCEDURE_ID, a.RDB$PROCEDURE_INPUTS,
    a.RDB$PROCEDURE_OUTPUTS, a.RDB$DESCRIPTION, a.RDB$PROCEDURE_SOURCE,
    a.RDB$PROCEDURE_BLR, a.RDB$SECURITY_CLASS, a.RDB$OWNER_NAME, a.RDB$RUNTIME,
    a.RDB$SYSTEM_FLAG, a.RDB$PROCEDURE_TYPE, a.RDB$VALID_BLR, a.RDB$DEBUG_INFO,
    a.RDB$ENGINE_NAME, a.RDB$ENTRYPOINT, a.RDB$PACKAGE_NAME, a.RDB$PRIVATE_FLAG,
    a.RDB$SQL_SECURITY
FROM SYSTEM.RDB$PROCEDURES a join PROCEDURE_IDS
  on a.RDB$PROCEDURE_ID = PROCEDURE_ID;

grant SELECT on table PUBLIC.RDB$PROCEDURES to PUBLIC;
