create or alter view PUBLIC.RDB$CHECK_CONSTRAINTS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
CONSTRAINTS As (
  Select distinct
    first_value(RDB$CONSTRAINT_NAME) over Win as CONSTRAINT_NAME,
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$CHECK_CONSTRAINTS c
    join SEARCH_PATH p on p.SCHEMA_NAME = c.RDB$SCHEMA_NAME
  Window Win As (partition by c.RDB$CONSTRAINT_NAME order by p.PRIO)
)SELECT a.RDB$CONSTRAINT_NAME, a.RDB$TRIGGER_NAME
FROM SYSTEM.RDB$CHECK_CONSTRAINTS a join CONSTRAINTS
  on a.RDB$CONSTRAINT_NAME=CONSTRAINT_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$CHECK_CONSTRAINTS to PUBLIC;
