create or alter view PUBLIC.RDB$PROCEDURE_PARAMETERS as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
PROCEDURES As (
  Select distinct
    first_value(RDB$SCHEMA_NAME) over Win as SCHEMA_NAME,
    first_value(RDB$PACKAGE_NAME) over Win as PACKAGE_NAME,
    first_value(RDB$PROCEDURE_NAME) over Win as PROCEDURE_NAME
  from SYSTEM.RDB$PROCEDURES r
    join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$SCHEMA_NAME
  Window Win As (partition by r.RDB$PACKAGE_NAME, r.RDB$PROCEDURE_NAME order by p.PRIO)
)
SELECT a.RDB$PARAMETER_NAME, a.RDB$PROCEDURE_NAME, a.RDB$PARAMETER_NUMBER,
    a.RDB$PARAMETER_TYPE, a.RDB$FIELD_SOURCE, a.RDB$DESCRIPTION,
    a.RDB$SYSTEM_FLAG, a.RDB$DEFAULT_VALUE, a.RDB$DEFAULT_SOURCE,
    a.RDB$COLLATION_ID, a.RDB$NULL_FLAG, a.RDB$PARAMETER_MECHANISM,
    a.RDB$FIELD_NAME, a.RDB$RELATION_NAME, a.RDB$PACKAGE_NAME
FROM SYSTEM.RDB$PROCEDURE_PARAMETERS a join PROCEDURES
  on a.RDB$PROCEDURE_NAME=PROCEDURE_NAME and
     a.RDB$PACKAGE_NAME is not distinct from PACKAGE_NAME and
     a.RDB$SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$PROCEDURE_PARAMETERS to PUBLIC;
