create or alter view PUBLIC.RDB$PUBLICATION_TABLES as
with SEARCH_PATH as (
  select row_number() over() as PRIO, NAME as SCHEMA_NAME
  from SYSTEM.RDB$SQL.PARSE_UNQUALIFIED_NAMES(rdb$get_context('SYSTEM', 'SEARCH_PATH'))
),
RELATIONS As (
  Select distinct
    first_value(RDB$TABLE_NAME) over Win as RELATION_NAME,
    first_value(RDB$TABLE_SCHEMA_NAME) over Win as SCHEMA_NAME
  from SYSTEM.RDB$PUBLICATION_TABLES r
    join SEARCH_PATH p on p.SCHEMA_NAME = r.RDB$TABLE_SCHEMA_NAME
  Window Win As (partition by r.RDB$TABLE_NAME order by p.PRIO)
)
SELECT a.RDB$PUBLICATION_NAME, a.RDB$TABLE_NAME
FROM SYSTEM.RDB$PUBLICATION_TABLES a join RELATIONS
  on a.RDB$TABLE_NAME=RELATION_NAME and
     a.RDB$TABLE_SCHEMA_NAME=SCHEMA_NAME;

grant SELECT on table PUBLIC.RDB$PUBLICATION_TABLES to PUBLIC;
